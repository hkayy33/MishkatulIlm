'use strict';

/**
 * Writes gitignored production env files from environment variables (CI / Docker build).
 *
 * Required:
 *   SUPABASE_ANON_KEY
 *
 * Optional (defaults shown):
 *   API_BASE_URL          — e.g. https://api.yourdomain.com
 *   SUPABASE_URL          — e.g. https://xxxx.supabase.co
 *   AUTH_REDIRECT_ORIGIN  — e.g. https://your-app.vercel.app (defaults to window.location.origin)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envDir = path.join(root, 'src/environments');

const apiBaseUrl = (process.env.API_BASE_URL || '').trim();
const supabaseUrl = (process.env.SUPABASE_URL || '').trim();
const supabaseAnonKey = (process.env.SUPABASE_ANON_KEY || '').trim();
function resolveAuthRedirectOrigin() {
  const explicit = (process.env.AUTH_REDIRECT_ORIGIN || '').trim();
  if (explicit) return explicit;
  const vercelHost = (process.env.VERCEL_URL || '').trim().replace(/^https?:\/\//, '');
  if (vercelHost) return `https://${vercelHost}`;
  return undefined;
}

const authRedirectOrigin = resolveAuthRedirectOrigin();

if (!supabaseAnonKey) {
  console.error('write-deploy-env: SUPABASE_ANON_KEY is required for production builds.');
  process.exit(1);
}

const deployTs = `/** Generated by scripts/write-deploy-env.cjs — do not edit. */
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  authRedirectOrigin: ${authRedirectOrigin ? JSON.stringify(authRedirectOrigin) : 'undefined as string | undefined'},
};
`;

const prodLocalTs = `/** Generated by scripts/write-deploy-env.cjs — do not edit. */
export const prodSecrets = {
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
};
`;

fs.mkdirSync(envDir, { recursive: true });
fs.writeFileSync(path.join(envDir, 'environment.deploy.ts'), deployTs, 'utf8');
fs.writeFileSync(path.join(envDir, 'environment.prod.local.ts'), prodLocalTs, 'utf8');
console.log('Wrote environment.deploy.ts and environment.prod.local.ts');
